def add_p(doc, text="", bold=False, italic=False, size=11, align=WD_ALIGN_PARAGRAPH.LEFT, space_before=0, space_after=3, color='000000'):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if text:
        r = p.add_run(text)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(size)
        r.bold = bold
        r.italic = italic
        r.font.color.rgb = RGBColor.from_string(color)
    return p

def add_h1(title):
    add_p(doc, title, bold=True, size=14, space_before=14, space_after=4, color='1F4E79')

def add_h2(title):
    add_p(doc, title, bold=True, size=12, space_before=10, space_after=3, color='2E75B6')

def add_box(title, text, summary_line=None):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = tbl.rows[0].cells[0]
    c.width = Inches(6.8)
    
    # borders and shading
    tcPr = c._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), 'F2F4F7')
    tcPr.append(shd)
    
    tcMar = OxmlElement('w:tcMar')
    for m in ['top', 'bottom', 'left', 'right']:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), '120' if m in ['top', 'bottom'] else '180')
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)
    
    p = c.paragraphs[0]
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.15
    r_t = p.add_run(title + "\n")
    r_t.font.name = 'Times New Roman'
    r_t.font.size = Pt(11)
    r_t.bold = True
    r_t.font.color.rgb = RGBColor.from_string('1F4E79')
    
    r_b = p.add_run(text)
    r_b.font.name = 'Times New Roman'
    r_b.font.size = Pt(10.5)
    
    if summary_line:
        p2 = c.add_paragraph()
        p2.paragraph_format.space_before = Pt(4)
        p2.paragraph_format.space_after = Pt(2)
        p2.paragraph_format.line_spacing = 1.15
        r_s_label = p2.add_run("▸ Сводка: ")
        r_s_label.font.name = 'Times New Roman'
        r_s_label.font.size = Pt(10.5)
        r_s_label.bold = True
        r_s_label.font.color.rgb = RGBColor.from_string('006600')
        r_s = p2.add_run(summary_line)
        r_s.font.name = 'Times New Roman'
        r_s.font.size = Pt(10.5)
        r_s.italic = True

