def sub(text, old, new, count=1):
    """Safe replacement: `old` must occur exactly `count` times (all occurrences are replaced)."""
    n = text.count(old)
    if n != count:
        raise ValueError('expected %d occurrence(s), found %d for: %r' % (count, n, old[:90]))
    return text.replace(old, new)


