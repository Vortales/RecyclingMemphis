def unify(text, law):
    """Заменяет разнобой наименований на единые обозначения внутри текста затрагиваемой статьи."""
    keep = {}
    for i, t in enumerate(_TITLES):
        ph = '\u0000%d\u0000' % i
        if t in text:
            keep[ph] = t
            text = text.replace(t, ph)
    for a, b in _RULES.get(law, []):
        text = text.replace(a, b)
    for ph, t in keep.items():
        text = text.replace(ph, t)
    return text
